import { NextResponse } from 'next/server'
import { ObjectId } from 'mongodb'
import { getDb } from '@/lib/mongodb'
import { TAG_OPTIONS } from '@/lib/stockRules'

export const dynamic = 'force-dynamic'

// PATCH /api/activities/:id — one-tap re-tag (e.g. Sold -> Own use, Arrived -> Returned).
// Only the meaning changes; quantities and stock are untouched.
export async function PATCH(
  request: Request,
  ctx: RouteContext<'/api/activities/[id]'>
) {
  try {
    const { id } = await ctx.params
    const { kind, soldPrice } = await request.json()

    if (!ObjectId.isValid(id)) {
      return NextResponse.json({ error: 'Invalid request' }, { status: 400 })
    }

    const db = await getDb()
    const activity = await db.collection('activities').findOne({ _id: new ObjectId(id) })
    if (!activity) {
      return NextResponse.json({ error: 'Entry not found' }, { status: 404 })
    }

    const updateFields: Record<string, unknown> = {}

    if (kind !== undefined && typeof kind === 'string') {
      const allowed = TAG_OPTIONS[activity.type as 'IN' | 'OUT'] ?? []
      if (!allowed.includes(kind as never)) {
        return NextResponse.json({ error: 'Not allowed for this entry' }, { status: 400 })
      }
      updateFields.kind = kind
    }

    if (soldPrice !== undefined) {
      if (soldPrice === null || soldPrice === '' || isNaN(Number(soldPrice))) {
        await db.collection('activities').updateOne({ _id: activity._id }, { $unset: { soldPrice: '' } })
      } else {
        updateFields.soldPrice = Number(soldPrice)
      }
    }

    if (Object.keys(updateFields).length > 0) {
      await db.collection('activities').updateOne({ _id: activity._id }, { $set: updateFields })
    }

    return NextResponse.json({ success: true })
  } catch (error) {
    console.error('Error tagging activity:', error)
    return NextResponse.json({ error: 'Failed to update entry' }, { status: 500 })
  }
}

// DELETE /api/activities/:id — void/undo an activity, restoring stock and deleting activity log (and clearing any related invoice).
export async function DELETE(
  _request: Request,
  ctx: RouteContext<'/api/activities/[id]'>
) {
  try {
    const { id } = await ctx.params

    if (!ObjectId.isValid(id)) {
      return NextResponse.json({ error: 'Invalid request' }, { status: 400 })
    }

    const db = await getDb()
    const activitiesColl = db.collection('activities')
    const colorwaysColl = db.collection('colorways')
    const invoicesColl = db.collection('invoices')

    const activity = await activitiesColl.findOne({ _id: new ObjectId(id) })
    if (!activity) {
      return NextResponse.json({ error: 'Entry not found' }, { status: 404 })
    }

    // 1. Revert inventory on the colorway if it exists
    if (activity.colorwayId && ObjectId.isValid(activity.colorwayId)) {
      const cw = await colorwaysColl.findOne({ _id: new ObjectId(activity.colorwayId) })
      if (cw) {
        let stockDelta = 0
        if (activity.type === 'OUT') {
          // Re-add to inventory
          stockDelta = activity.quantityChange || 1
        } else if (activity.type === 'IN') {
          // Subtract from inventory
          stockDelta = -(activity.quantityChange || 1)
        }

        const newQty = Math.max(0, (cw.quantityAvailable || 0) + stockDelta)
        const updateDoc: Record<string, unknown> = {
          quantityAvailable: newQty,
          updatedAt: new Date(),
        }

        if (activity.subVariantLabel && Array.isArray(cw.breakdown)) {
          updateDoc.breakdown = cw.breakdown.map((b: { id: string; label: string; quantity: number }) => {
            if (b.label === activity.subVariantLabel) {
              return { ...b, quantity: Math.max(0, b.quantity + stockDelta) }
            }
            return b
          })
        }

        await colorwaysColl.updateOne(
          { _id: cw._id },
          { $set: updateDoc }
        )
      }
    }

    // 2. If this activity was generated by an invoice, check if the invoice should also be voided/cleaned
    if (activity.invoiceId) {
      const invoiceIdQuery = ObjectId.isValid(activity.invoiceId) ? new ObjectId(activity.invoiceId) : activity.invoiceId
      const invoice = await invoicesColl.findOne({ _id: invoiceIdQuery })
      if (invoice) {
        const remainingActivities = await activitiesColl.countDocuments({
          invoiceId: activity.invoiceId,
          _id: { $ne: activity._id },
        })
        if (remainingActivities === 0) {
          await invoicesColl.deleteOne({ _id: invoice._id })
        } else {
          const price = activity.soldPrice || 0
          const qty = activity.quantityChange || 1
          const itemSubtotal = price * qty
          const updatedItems = Array.isArray(invoice.items)
            ? invoice.items.filter((it: { colorwayId: string }) => it.colorwayId !== activity.colorwayId)
            : []
          await invoicesColl.updateOne(
            { _id: invoice._id },
            {
              $inc: { totalAmount: -itemSubtotal },
              $set: { items: updatedItems },
            }
          )
        }
      }
    }

    // 3. Delete the activity from activities collection
    await activitiesColl.deleteOne({ _id: activity._id })

    return NextResponse.json({
      success: true,
      message: 'Sale voided and stock restored successfully.',
      restoredCode: activity.fullCode,
    })
  } catch (error) {
    console.error('Error voiding activity:', error)
    return NextResponse.json({ error: 'Failed to void activity' }, { status: 500 })
  }
}

